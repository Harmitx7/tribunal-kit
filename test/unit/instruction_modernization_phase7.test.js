'use strict';

/**
 * instruction_modernization_phase7.test.js
 * ══════════════════════════════════════════════════════════════════════════════
 * Phase 7: Workflow & Instruction Modernization Verification Suite
 *
 * Verifies:
 *   1. Instruction Hierarchy & Kernel Context Budget (< 5,000 bytes)
 *   2. Core Protocol Invariants (Anti-Hallucination, Fabel L1-L5, SDD/TDD, VBC)
 *   3. All 52 Workflows Frontmatter & Required-Skill / Script-Binding Resolution
 *   4. Zero Deprecated Directories (runners/) or Stale Path References
 *   5. Reviewer Count Invariant (28 reviewers) across all Rule & Workflow Sources
 *   6. Skill Inventory & Skill-Topic-Map 100% Registry Parity
 *   7. Absence of Legacy Announcement Format ("Applying knowledge of @") across all Bridges
 *   8. Deterministic Instruction Validator Engine & Adversarial Detection
 */

const fs = require('fs');
const path = require('path');
const {
  validateWorkflows,
  validateHostInstructions,
  validateSkillRegistry,
  runAllValidations,
  EXPECTED_REVIEWER_COUNT,
  EXPECTED_SKILL_COUNT,
  MAX_KERNEL_BRIDGE_BYTES,
} = require('../../scripts/validate-instructions');

const REPO_ROOT = path.resolve(__dirname, '../..');
const PACKAGE_VERSION = require('../../package.json').version;

describe('Phase 7: Workflow & Instruction Modernization', () => {

  // ── 1. INSTRUCTION HIERARCHY & KERNEL CONTEXT BUDGET ─────────────────────────
  describe('1. Instruction Hierarchy & Kernel Context Budget', () => {
    const kernelPath = path.join(REPO_ROOT, '.agent', 'rules', 'kernel.md');

    test('kernel.md exists and is within lean context budget (< 5,000 bytes when bridged)', () => {
      expect(fs.existsSync(kernelPath)).toBe(true);
      const kernelContent = fs.readFileSync(kernelPath, 'utf8');
      const bridgeHeader = '# Tribunal Kit — Cursor Bridge\n# Auto-generated by tribunal-kit init. Do not edit manually.\n# Source: .agent/rules/kernel.md\n\n';
      const totalBytes = Buffer.byteLength(bridgeHeader + kernelContent, 'utf8');

      expect(totalBytes).toBeLessThan(MAX_KERNEL_BRIDGE_BYTES);
    });

    test('kernel.md preserves all core safety protocols and evidence invariants', () => {
      const content = fs.readFileSync(kernelPath, 'utf8');

      // Fabel Protocol
      expect(content).toContain('Fabel Protocol');
      expect(content).toContain('L1:');
      expect(content).toContain('L5:');

      // Anti-Hallucination
      expect(content).toContain('Anti-Hallucination Protocol (Non-Negotiable)');
      expect(content).toContain('Never import packages not verified in package.json');
      expect(content).toContain('Never call undocumented or invented framework methods');

      // Routing & Activity Protocol
      expect(content).toContain('Automatic Specialist Agent Routing');
      expect(content).toContain('Tribunal Activity Protocol');
      expect(content).toContain('› **Activated**');
      expect(content).toContain('✔ **Verified**');
      expect(content).toContain('✖ **Failed**');

      // SDD & TDD
      expect(content).toContain('Iron Law of TDD');
      expect(content).toContain('Verification-Before-Completion (VBC)');

      // Inventory Pointer
      expect(content).toContain(`${EXPECTED_SKILL_COUNT} deep skill modules`);
      expect(content).toContain('.agent/skills/<skill-name>/SKILL.md');
      expect(content).toContain('.agent/rules/GEMINI.md');
    });
  });

  // ── 2. REVIEWER COUNT & SPECIFICATION PARITY ────────────────────────────────
  describe('2. Reviewer Count Invariant Parity (28 Reviewers)', () => {
    test('standard reviewer count is exactly 28 across all governance files', () => {
      expect(EXPECTED_REVIEWER_COUNT).toBe(28);

      const filesToCheck = [
        path.join(REPO_ROOT, '.agent', 'rules', 'GEMINI.md'),
        path.join(REPO_ROOT, '.agent', 'rules', 'kernel.md'),
        path.join(REPO_ROOT, '.agent', 'config', 'system-prompt.md'),
        path.join(REPO_ROOT, '.agent', 'workflows', 'tribunal-full.md'),
        path.join(REPO_ROOT, 'AGENTS.md'),
        path.join(REPO_ROOT, 'CLAUDE.md'),
        path.join(REPO_ROOT, '.cursorrules'),
        path.join(REPO_ROOT, '.windsurfrules'),
      ];

      for (const file of filesToCheck) {
        if (fs.existsSync(file)) {
          const content = fs.readFileSync(file, 'utf8');
          expect(content).not.toContain('31 reviewers');
        }
      }
    });

    test('system-prompt.md reflects current skill count, 28 reviewers, and package version', () => {
      const spPath = path.join(REPO_ROOT, '.agent', 'config', 'system-prompt.md');
      const content = fs.readFileSync(spPath, 'utf8');

      expect(content).toContain(String(EXPECTED_SKILL_COUNT));
      expect(content).not.toContain('185-skill library');
      expect(content).not.toContain('235 skills');
      expect(content).not.toContain('320 skills');
      expect(content).not.toContain('v9.2.6');
      expect(content).toContain(`v${PACKAGE_VERSION}`);
    });
  });

  // ── 3. WORKFLOW DEFINITION INTEGRITY & RESOLUTION ───────────────────────────
  describe('3. Workflow Definition Integrity & Resolution', () => {
    const wfDir = path.join(REPO_ROOT, '.agent', 'workflows');

    test('all 52 workflow files possess valid frontmatter and descriptions', () => {
      const files = fs.readdirSync(wfDir).filter(f => f.endsWith('.md'));
      expect(files.length).toBe(52);

      const res = validateWorkflows(REPO_ROOT);
      expect(res.errors).toEqual([]);
      expect(res.checked).toBe(52);
    });

    test('all required-skills in workflows resolve to existing skills on disk', () => {
      const files = fs.readdirSync(wfDir).filter(f => f.endsWith('.md'));
      const skillsDir = path.join(REPO_ROOT, '.agent', 'skills');

      for (const file of files) {
        const content = fs.readFileSync(path.join(wfDir, file), 'utf8');
        const match = content.match(/required-skills:\s*\n((?:\s+-\s+[^\n]+\n)+)/);
        if (match) {
          const list = match[1].split('\n').map(s => s.replace(/^\s+-\s+/, '').trim()).filter(Boolean);
          for (const s of list) {
            expect(fs.existsSync(path.join(skillsDir, s, 'SKILL.md'))).toBe(true);
          }
        }
      }
    });

    test('all scripts-binding entries in workflows resolve to existing scripts on disk', () => {
      const files = fs.readdirSync(wfDir).filter(f => f.endsWith('.md'));

      for (const file of files) {
        const content = fs.readFileSync(path.join(wfDir, file), 'utf8');
        const match = content.match(/scripts-binding:\s*\n((?:\s+-\s+[^\n]+\n)+)/);
        if (match) {
          const list = match[1].split('\n').map(s => s.replace(/^\s+-\s+/, '').trim()).filter(Boolean);
          for (const s of list) {
            expect(fs.existsSync(path.join(REPO_ROOT, s))).toBe(true);
          }
        }
      }
    });

    test('zero workflows contain deprecated runners/ directory references', () => {
      const files = fs.readdirSync(wfDir).filter(f => f.endsWith('.md'));

      for (const file of files) {
        const content = fs.readFileSync(path.join(wfDir, file), 'utf8');
        expect(content).not.toContain('node runners/');
        expect(content).not.toContain('runners/skill_enhancement_engine.js');
      }
    });
  });

  // ── 4. SKILL & TOPIC MAP REGISTRY PARITY ────────────────────────────────────
  describe('4. Skill & Topic Map Registry Parity', () => {
    test('topic map registers skills with zero missing or phantom skills', () => {
      const res = validateSkillRegistry(REPO_ROOT);
      expect(res.errors).toEqual([]);
      expect(res.checked).toBe(EXPECTED_SKILL_COUNT);
    });

    test('all 39 domain reference documents exist on disk', () => {
      const tmPath = path.join(REPO_ROOT, '.agent', 'skill_topic_map.json');
      const topicMap = JSON.parse(fs.readFileSync(tmPath, 'utf8'));

      let refCount = 0;
      for (const refs of Object.values(topicMap.domain_references || {})) {
        for (const ref of refs) {
          refCount++;
          expect(fs.existsSync(path.join(REPO_ROOT, ref))).toBe(true);
        }
      }
      expect(refCount).toBe(39);
    });
  });

  // ── 5. HOST BRIDGE CONSISTENCY & LEGACY PATTERN REMOVAL ─────────────────────
  describe('5. Host Bridge Consistency & Legacy Pattern Removal', () => {
    const bridgeFiles = [
      path.join(REPO_ROOT, 'AGENTS.md'),
      path.join(REPO_ROOT, 'CLAUDE.md'),
      path.join(REPO_ROOT, '.cursorrules'),
      path.join(REPO_ROOT, '.windsurfrules'),
      path.join(REPO_ROOT, '.github', 'copilot-instructions.md'),
      path.join(REPO_ROOT, '.gemini', 'GEMINI.md'),
      path.join(REPO_ROOT, '.claude', 'CLAUDE.md'),
    ];

    test('all host bridge files are free of legacy "Applying knowledge of @" format', () => {
      for (const b of bridgeFiles) {
        if (fs.existsSync(b)) {
          const content = fs.readFileSync(b, 'utf8');
          expect(content).not.toContain('Applying knowledge of @');
        }
      }
    });

    test('all host bridges mandate the standardized › **Activated** announcement format', () => {
      for (const b of bridgeFiles) {
        if (fs.existsSync(b)) {
          const content = fs.readFileSync(b, 'utf8');
          expect(content).toContain('› **Activated**');
        }
      }
    });
  });

  // ── 6. DETERMINISTIC INSTRUCTION VALIDATOR ENGINE ───────────────────────────
  describe('6. Deterministic Instruction Validator Engine', () => {
    test('runAllValidations reports pass across the repository', () => {
      const res = runAllValidations(REPO_ROOT);
      expect(res.passed).toBe(true);
      expect(res.errors).toEqual([]);
      expect(res.metrics.workflowsChecked).toBe(52);
      expect(res.metrics.skillsChecked).toBe(EXPECTED_SKILL_COUNT);
    });

    test('adversarial validation catches malformed workflow, missing skills, and runner references', () => {
      const tempDir = fs.mkdtempSync(path.join(REPO_ROOT, 'test', 'fixtures', 'temp_wf_val_'));
      const agentDir = path.join(tempDir, '.agent');
      const wfDir = path.join(agentDir, 'workflows');
      fs.mkdirSync(wfDir, { recursive: true });

      // Malformed workflow
      fs.writeFileSync(
        path.join(wfDir, 'bad_workflow.md'),
        '---\ndescription: short\nrequired-skills:\n  - non-existent-skill\n---\nRun node runners/bad_script.js with 31 reviewers\n'
      );

      const res = validateWorkflows(tempDir);
      expect(res.errors.length).toBeGreaterThanOrEqual(3);
      expect(res.errors.some(e => e.includes('non-existent-skill'))).toBe(true);
      expect(res.errors.some(e => e.includes('runners/'))).toBe(true);
      expect(res.errors.some(e => e.includes('31 reviewers'))).toBe(true);

      fs.rmSync(tempDir, { recursive: true, force: true });
    });
  });
});

